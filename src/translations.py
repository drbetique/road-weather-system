def get_translation(key: str, lang: str = "fi") -> str:
    """Get translation for key in specified language"""
    if lang not in TRANSLATIONS:
        lang = "fi"
    return TRANSLATIONS[lang].get(key, key)


def get_all_translations(lang: str = "fi") -> dict:
    """Get all translations for specified language"""
    if lang not in TRANSLATIONS:
        lang = "fi"
    return TRANSLATIONS[lang]


